function descriptionKey(id:string){
  if(descriptions[id])return id
  if(id.startsWith('wiring_')||id.endsWith('_cable')||id==='photo_blowdown_wiring'||id.startsWith('cascade_signal_')||id==='cascade_pressure_signal')return 'wiring'
  if(id.startsWith('da_recirculation_'))return 'da_recirculation'
  if(id.startsWith('cascade_consumer_'))return 'cascade_consumer'
  if(id.startsWith('cascade_distribution_pocket_'))return 'cascade_distribution_pocket'
  if(id.startsWith('cascade_distribution_leg_'))return 'cascade_distribution_leg'
  if(id.startsWith('cascade_distribution_drain_')||['fv_to_trap_gap','trap_gap_to_bdv'].includes(id))return 'condensate'
  if(id.startsWith('tds_')||id.startsWith('cascade_tds_'))return 'tds'
  if(id.startsWith('bottom_')||id.startsWith('cascade_bottom_'))return 'bottom'
  if(id.startsWith('steam_')||id.startsWith('cascade_steam_')||id==='cascade_distribution_supply'||id==='gpz_bypass')return 'steam'
  if(['suction_common','pump_delivery','deaerator_feed','da_feed_out','feed_inlet_adapter','direct_inlet','to_direct','to_economizer','from_economizer','eco_after_modulation','eco_inlet_adapter','mod_eco_bypass','mod_direct_bypass','cascade_feed_header'].includes(id)||id.startsWith('pump_branch_')||id.startsWith('cascade_suction_'))return 'feed'
  if(id==='cascade_pressure_connection')return 'pressure_header'
  return undefined
}

export function partInformation(part:FamilyPart,config:FamilyConfig):PartInformation {
  const id=part.id.replace(/^unit\d+:/,''),count=boilerCount(config.cascade),key=descriptionKey(id)
  const text=key?descriptions[key]:{summary:'Элемент обвязки котельной.',benefits:['Обеспечивает соединение и обслуживание оборудования.'],details:[]}
  const specs:string[]=[]
  if(['boiler','boiler_door_labels','premium_logo'].includes(id))specs.push(`${config.power.toLocaleString('ru-RU')} кг/ч на котёл`,`${config.pressure} бар · ${trims.find(t=>t.id===config.trim)!.label}`)
  if(id==='deaerator')specs.push(deaeratorLabels[selectDeaerator(config.power,count)],`Подбор для ${config.power*count/1000} т/ч суммарной производительности`)
  if(id==='plus_cabinet')specs.push('Корпус 650 × 500 × 220 мм',config.trim==='comfort'?'Экран на 20% меньше, чем в «Комфорт+»':'Сенсорная панель и четыре прибора на двери')
  if(id==='cascade_cabinet')specs.push('Корпус 400 × 400 × 150 мм',`${count} ${count===5?'котлов':'котла'} в выбранном каскаде`)
  if(id==='cascade_header')specs.push(`${config.power*count/1000} т/ч суммарно`)
  if(id==='cascade_distribution')specs.push('Диаметр корпуса в сборке — Ø426 мм','Три выхода к потребителям')
  const dimension=part.label.match(/(?:DN|Ø)\d+(?:[,.]\d+)?(?:\s*→\s*(?:DN|Ø)?\d+(?:[,.]\d+)?)?|L=\d+\s*мм|0[–-]1,6\s*МПа/g)
  if(dimension&&!['cascade_distribution','deaerator'].includes(id))specs.push(...dimension)
  const requires=part.requires||[],excludes=part.excludes||[]
  let availability=''
  if(requires.includes('comfort_plus'))availability='Только в комплектации «Комфорт+».'
  else if(requires.includes('comfort'))availability='Входит в комплектации «Комфорт» и «Комфорт+».'
  else if(requires.includes('standard')||['control_cabinet','cabinet_door','cabinet_interior'].includes(id))availability='В этой форме предусмотрен в комплектации «Стандарт».'
  else if(excludes.includes('comfort_plus'))availability='Входит в комплектации «Стандарт» и «Комфорт».'
  if(id==='plus_cabinet')availability=`Шкаф выбранной комплектации «${config.trim==='comfort'?'Комфорт':'Комфорт+'}».`
  const option=(['modulation','gpz','economizer','burner','deaerator','bdv','fv'] as const).find(o=>requires.includes(o)||id===o)
  const optionCopy:Record<string,string>={modulation:'Дополнительная опция для «Комфорт» и «Комфорт+».',gpz:config.power>=4000?'Входит в комплектацию S-4000 и S-5000.':'Дополнительная опция дистанционного управления.',economizer:'Дополнительное оборудование для котлов от 1500 кг/ч.',burner:'Показан при выборе дополнения «Горелка».',deaerator:'Предусмотрен при выборе деаэратора.',bdv:'Предусмотрен при выборе бака продувки BDV.',fv:'Предусмотрен при выборе сепаратора FV.'}
  if(option)availability=[availability,optionCopy[option]].filter(Boolean).join(' ')
  if(id.startsWith('da_')&&selectDeaerator(config.power,count)==='da3'&&['da_safety_group','da_level_sensor','da_electric_valve','da_pressure_header','da_pressure_siphon','da_instrument_tray'].includes(id))availability='Узел обвязки ДА-3. Появляется при выборе этого деаэратора.'
  if(id.startsWith('cascade_'))availability=[availability,`Входит в обвязку каскада из ${count} котлов.`].filter(Boolean).join(' ')
  return {...text,specs,availability,covered:!!key}
}
