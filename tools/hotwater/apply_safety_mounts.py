"""Apply source-verified mounting metadata without changing any CAD or GLB.

20.10.2026, Codex / GPT-6. Input evidence is generated by build_safety_mounts.py.
The reused valve is a visual shape, not a DN/PN or medium compatibility claim.
"""
import argparse
import hashlib
import json
from pathlib import Path


def read(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main():
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("evidence", type=Path)
    args = parser.parse_args()
    evidence = read(args.evidence)
    catalog_path = root / "src/assets/hotwater/catalog.json"
    catalog = read(catalog_path)
    sources = {row["id"]: row for row in evidence["models"]}
    assert set(sources) == {row["id"] for row in catalog["models"]}
    fields = ("position", "axis", "outletDirection", "sourceNode", "sourceName",
              "sourceFlangeDN", "sourceFlangePN")
    for model in catalog["models"]:
        source = sources[model["id"]]
        assert source["sourceSha256"] == model["sourceSha256"]
        assert source["assetSha256"] == model["assetSha256"]
        assert len(source["mounts"]) == (1 if model["family"] == "cla" else 2)
        model["safetyMounts"] = [{key: mount[key] for key in fields} for mount in source["mounts"]]
    valve_path = root / "tools/hotwater/safety-valve-mounting.json"
    valve = read(valve_path)
    assert hashlib.sha256((catalog_path.parent / valve["asset"]).read_bytes()).hexdigest() == valve["assetSha256"]
    accessories_path = catalog_path.parent / "catalog-accessories.json"
    accessories = read(accessories_path)
    for rows in (catalog["accessories"], accessories):
        spec = next(row for row in rows if row["id"] == "relief-shape")
        spec["mounting"] = valve["mounting"]
        spec["label"] = "Сбросные клапаны · на патрубках котла"
        spec["description"] = "Показывает положение клапанов на заводских патрубках и доступ к ним. Количество определяется выбранной сборкой."
        spec["notes"] = "Посадочные места взяты из заводской сборки. Показана исходная габаритная форма клапана DN40 без изменения масштаба; размеры фланцев у котлов различаются. Исполнение клапана, DN, рабочая среда и давление настройки выбираются по проекту."
    write(catalog_path, catalog)
    write(accessories_path, accessories)
    print(json.dumps({"models": len(sources), "mounts": sum(len(row["mounts"]) for row in sources.values()),
                      "geometryChanged": False}))


if __name__ == "__main__":
    main()
